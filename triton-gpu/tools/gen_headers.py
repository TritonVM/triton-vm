#!/usr/bin/env python3
"""Generate kernels/common/tg_tip5_tables.h and tg_tip5_mds.h from twenty-first's tip5/mod.rs.

Usage: python3 tools/gen_headers.py path/to/twenty-first/src/tip5/mod.rs
"""
import re, sys, pathlib

P = 0xFFFF_FFFF_0000_0001
src = pathlib.Path(sys.argv[1]).read_text()
out = pathlib.Path(__file__).resolve().parent.parent / "kernels" / "common"

lut = re.search(r"pub const LOOKUP_TABLE: \[u8; 256\] = \[(.*?)\];", src, re.S).group(1)
lut = [int(x) for x in re.findall(r"\d+", lut)]
assert len(lut) == 256 and sorted(lut) == list(range(256))
rc = re.search(r"pub const ROUND_CONSTANTS.*?= \[(.*?)\];", src, re.S).group(1)
rc = [int(x) for x in re.findall(r"BFieldElement::new\((\d+)\)", rc)]
assert len(rc) == 80
rc_mont = [(c << 64) % P for c in rc]  # Montgomery representation, as BFieldElement::new stores it

def fmt(vals, per_line, wrap):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(wrap(v) for v in vals[i:i + per_line]) + ",")
    return "\n".join(lines)

(out / "tg_tip5_tables.h").write_text(f"""// GENERATED by tools/gen_headers.py from twenty-first's tip5/mod.rs. Do not edit.
#pragma once

// Tip5 split-and-lookup table (applied byte-wise to the Montgomery representation).
TG_LUT_ARRAY(TG_TIP5_LOOKUP_TABLE, 256) = {{
{fmt(lut, 16, str)}
}};

// Tip5 round constants, already in Montgomery representation (raw u64).
TG_CONST_ARRAY(u64, TG_TIP5_ROUND_CONSTANTS, 80) = {{
{fmt(rc_mont, 3, lambda v: f"U64C({v})")}
}};
""")

body = re.search(r"pub\(super\) fn generated_function<T: WrappingArithmetic>\(\s*input: \[T; STATE_SIZE\],\s*\) -> \[T; STATE_SIZE\] \{(.*?)\n    \}\n", src, re.S).group(1)
body = re.sub(r"\s+", " ", body).strip()
stmts, ret = body.rsplit(";", 1)
stmts = stmts.split(";")
ret = ret.strip()
assert ret.startswith("[") and ret.endswith("]")
ret_items = [x.strip() for x in ret[1:-1].split(",") if x.strip()]
assert len(ret_items) == 16

def conv(expr):
    expr = re.sub(r",\s*\)", ")", expr)
    expr = re.sub(r"wrapping_mul\((\d+)\)", r"wrapping_mul(U64C(\1))", expr)
    return expr

cpp = []
for s in stmts:
    s = s.strip()
    m = re.match(r"let (node_\d+) = (.*)$", s)
    assert m, s
    cpp.append(f"    const TgW {m.group(1)} = {conv(m.group(2))};")
for i, r in enumerate(ret_items):
    cpp.append(f"    out[{i}] = ({conv(r)}).v;")

(out / "tg_tip5_mds.h").write_text("""// GENERATED by tools/gen_headers.py from twenty-first's Tip5::generated_function. Do not edit.
// 16 * (circulant MDS matrix) * input, in wrapping u64 arithmetic (Karatsuba-style cyclic convolution).
#pragma once

#include "tg_arith.h"

struct TgW {
    u64 v;
    TG_MFN TgW wrapping_add(TgW o) const { TgW r; r.v = v + o.v; return r; }
    TG_MFN TgW wrapping_sub(TgW o) const { TgW r; r.v = v - o.v; return r; }
    TG_MFN TgW wrapping_mul(u64 c) const { TgW r; r.v = tg_mul_const(v, c); return r; }
};

TG_FN void tg_tip5_mds_generated_function(TG_THREAD const u64 *in_raw, TG_THREAD u64 *out) {
    TgW input[16];
    TG_UNROLL
    for (int i = 0; i < 16; ++i) { input[i].v = in_raw[i]; }
""" + "\n".join(cpp) + "\n}\n")
print("ok:", len(stmts), "statements")
